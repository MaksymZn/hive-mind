"""Bundle hive-mind's ES modules into ONE self-contained HTML file.

Why: browsers refuse to load `<script type="module">` imports from a page
opened as a file (file://), so the normal project needs a local server.
This script inlines every module into a classic <script>, so the result
opens with a double-click, no Node/Vite/Python server needed.

How (the same idea webpack/Vite use internally):
  * each src/*.js file becomes a function in a small module table;
  * `import { a as b } from './x.js'` -> `const { a: b } = __require('src/x.js');`
  * `export function|class|const NAME` -> plain declaration, NAME is
    returned from the module function;
  * modules run once, lazily, on first __require (like ES modules).

Usage (from the repository root):
    py tools/build_standalone.py
Optional arguments: <project_dir> <output.html>
(defaults: the repository root and standalone/hive-mind.html).

Re-run it after every change in src/ — standalone/hive-mind.html is a
generated file and should never be edited by hand.
"""
import re
import sys
from pathlib import Path, PurePosixPath

IMPORT_RE = re.compile(r"^import\s*\{([^}]*)\}\s*from\s*'([^']+)';[ \t]*$", re.M | re.S)
EXPORT_DECL_RE = re.compile(r"^export\s+(function|class|const)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_EMPTY_RE = re.compile(r"^export\s*\{\s*\};[ \t]*$", re.M)
ENTRY_TAG_RE = re.compile(r'<script type="module" src="/src/main\.js"></script>')


def resolve(from_module: str, spec: str) -> str:
    """'src/models/State.js' + '../config.js' -> 'src/config.js'."""
    parts = []
    for part in (PurePosixPath(from_module).parent / spec).parts:
        if part == "..":
            parts.pop()
        elif part != ".":
            parts.append(part)
    return "/".join(parts)


def transform(module: str, source: str):
    deps = []

    def repl_import(m):
        names = []
        for item in m.group(1).split(","):
            item = item.strip()
            if not item:
                continue
            if " as " in item:
                original, alias = (s.strip() for s in item.split(" as "))
                names.append(f"{original}: {alias}")
            else:
                names.append(item)
        target = resolve(module, m.group(2))
        deps.append(target)
        return f"const {{ {', '.join(names)} }} = __require('{target}');"

    source = IMPORT_RE.sub(repl_import, source)

    exports = EXPORT_DECL_RE.findall(source)
    source = EXPORT_DECL_RE.sub(lambda m: f"{m.group(1)} {m.group(2)}", source)
    source = EXPORT_EMPTY_RE.sub("", source)

    leftover = re.findall(r"^\s*(import|export)\b.*$", source, re.M)
    if leftover:
        raise SystemExit(f"{module}: unsupported import/export syntax left: {leftover}")

    names = ", ".join(name for _, name in exports)
    return source, deps, names


def main():
    repo_root = Path(__file__).resolve().parent.parent
    project = Path(sys.argv[1]) if len(sys.argv) > 1 else repo_root
    out_file = Path(sys.argv[2]) if len(sys.argv) > 2 else project / "standalone" / "hive-mind.html"

    modules, order, seen = {}, [], set()

    def visit(module):
        if module in seen:
            return
        seen.add(module)
        source = (project / module).read_text(encoding="utf-8")
        body, deps, names = transform(module, source)
        for dep in deps:
            visit(dep)
        modules[module] = (body, names)
        order.append(module)

    visit("src/main.js")

    chunks = [
        "// Hive Mind - standalone build (all ES modules bundled into one classic script).",
        "// Generated by tools/build_standalone.py from the files in src/ - edit those, not this.",
        "(function () {",
        "  'use strict';",
        "  const __factories = Object.create(null);",
        "  const __cache = Object.create(null);",
        "  function __require(name) {",
        "    if (!(name in __cache)) {",
        "      __cache[name] = {}; // guards against import cycles",
        "      __cache[name] = __factories[name]();",
        "    }",
        "    return __cache[name];",
        "  }",
    ]
    for module in order:
        body, names = modules[module]
        if "</script" in body.lower():
            raise SystemExit(f"{module}: contains '</script', cannot inline")
        chunks.append(f"\n  // ===== {module} =====")
        # ES modules are always strict mode; keep that inside every factory.
        chunks.append(f"  __factories['{module}'] = function () {{\n'use strict';\n{body}\nreturn {{ {names} }};\n  }};")
    chunks.append("\n  __require('src/main.js');")
    chunks.append("})();")
    bundle = "\n".join(chunks)

    html = (project / "index.html").read_text(encoding="utf-8")
    if not ENTRY_TAG_RE.search(html):
        raise SystemExit("index.html: entry <script type=module> tag not found")
    html = ENTRY_TAG_RE.sub(lambda _m: "<script>\n" + bundle + "\n</script>", html)

    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(html, encoding="utf-8", newline="\n")
    print(f"Bundled {len(order)} modules -> {out_file} ({out_file.stat().st_size // 1024} KB)")
    print("Order:", " -> ".join(order))


if __name__ == "__main__":
    main()
